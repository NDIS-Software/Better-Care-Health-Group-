export function getServices(locale: Locale) {
  if (locale === "en") return services;
  return services.map((service) => ({ ...service, ...chinese[service.slug] }));
}

export function getServiceGroups(locale: Locale) {
  if (locale === "en") return serviceGroups;
  const localized = getServices(locale);
  const fromGroup = (group: typeof services) => group.map((service) => localized.find(({ slug }) => slug === service.slug)!);
  return {
    clinical: fromGroup(serviceGroups.clinical),
    earlyChildhood: fromGroup(serviceGroups.earlyChildhood),
    dailyLiving: fromGroup(serviceGroups.dailyLiving),
    community: fromGroup(serviceGroups.community),
  };
}
